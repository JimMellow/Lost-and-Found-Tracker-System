    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        String name = itemName.getText().trim();
        String color = colorName.getText().trim();
        String description = descriptionArea.getText().trim();
        String location = locationName.getText().trim();
        String date = dateReported.getText().trim();
        String status = statusComboBox.getSelectedItem().toString();

        if (name.isEmpty() || color.isEmpty() || description.isEmpty()
                || location.isEmpty() || date.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please fill in all required fields.");
            return;
        }

        java.sql.Date sqlDate;

        try {
            java.time.LocalDate parsedDate = java.time.LocalDate.parse(
                    date,
                    java.time.format.DateTimeFormatter.ISO_LOCAL_DATE
            );
            sqlDate = java.sql.Date.valueOf(parsedDate);
        } catch (java.time.DateTimeException e) {
            JOptionPane.showMessageDialog(this,
                    "Enter a valid date in YYYY-MM-DD format.");
            return;
        }

        String checkSql = "SELECT item_id, item_name, item_color, "
                + "description, location, item_status FROM items "
                + "WHERE is_archived = FALSE "
                + "AND item_status = ? "
                + "AND LOWER(TRIM(item_name)) = LOWER(TRIM(?)) "
                + "AND LOWER(TRIM(location)) = LOWER(TRIM(?)) "
                + "AND LOWER(TRIM(COALESCE(item_color, ''))) "
                + "= LOWER(TRIM(?))";

        String insertSql = "INSERT INTO items "
                + "(item_name, item_color, description, location, "
                + "date_reported, item_status) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection con = connector.getConnection()) {
            if (con == null) {
                JOptionPane.showMessageDialog(this,
                        "Database connection failed.");
                return;
            }

            try (PreparedStatement check = con.prepareStatement(checkSql)) {
                check.setString(1, status);
                check.setString(2, name);
                check.setString(3, location);
                check.setString(4, color);

                try (java.sql.ResultSet rs = check.executeQuery()) {
                    if (rs.next()) {
                        JOptionPane.showMessageDialog(this,
                                "A similar active item already exists!\n\n"
                                + "Item ID: " + rs.getInt("item_id")
                                + "\nName: " + rs.getString("item_name")
                                + "\nColor: " + rs.getString("item_color")
                                + "\nDescription: " + rs.getString("description")
                                + "\nLocation: " + rs.getString("location")
                                + "\nStatus: " + rs.getString("item_status")
                                + "\n\nPlease review the existing report first.",
                                "Possible Duplicate",
                                JOptionPane.WARNING_MESSAGE);
                        return;
                    }
                }
            }

            try (PreparedStatement pst = con.prepareStatement(insertSql)) {
                pst.setString(1, name);
                pst.setString(2, color);
                pst.setString(3, description);
                pst.setString(4, location);
                pst.setDate(5, sqlDate);
                pst.setString(6, status);

                pst.executeUpdate();

                JOptionPane.showMessageDialog(this,
                        "Item saved successfully!");

                itemName.setText("");
                colorName.setText("");
                descriptionArea.setText("");
                locationName.setText("");
                dateReported.setText("");
                statusComboBox.setSelectedIndex(0);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Unable to save item:\n" + e.getMessage());
        }
    }//GEN-LAST:event_saveButtonActionPerformed

